use crate::cli::args::OutputFormat;
use crate::planner::generator::CommitPlan;

pub struct PlanFormatter;

impl PlanFormatter {
    pub fn format(plan: &CommitPlan, format: OutputFormat, dry_run: bool) -> Result<String, String> {
        match format {
            OutputFormat::Markdown => Ok(Self::format_markdown(plan)),
            OutputFormat::Json => serde_json::to_string_pretty(plan)
                .map_err(|e| format!("Failed to serialize plan to JSON: {}", e)),
            OutputFormat::Shell => Ok(Self::format_shell(plan, dry_run)),
        }
    }

    pub fn format_markdown(plan: &CommitPlan) -> String {
        let mut out = String::new();
        out.push_str("# VibeCommit Execution Plan\n\n");
        out.push_str(&format!(
            "**Total Commits**: {} | **Files Changed**: {} | **Diff Stats**: +{} -{}\n\n",
            plan.commits.len(),
            plan.total_files,
            plan.total_additions,
            plan.total_deletions
        ));

        if plan.commits.is_empty() {
            out.push_str("No changes detected in diff.\n");
            return out;
        }

        // Summary Table
        out.push_str("| # | Type | Scope | Title | Files | Diff |\n");
        out.push_str("|---|---|---|---|---|---|\n");
        for commit in &plan.commits {
            out.push_str(&format!(
                "| {} | `{}` | `{}` | {} | {} | +{} -{} |\n",
                commit.index,
                commit.commit_type.as_str(),
                commit.scope,
                commit.title,
                commit.files.len(),
                commit.additions,
                commit.deletions
            ));
        }
        out.push_str("\n---\n\n");

        // Detailed Commit Breakdown
        for commit in &plan.commits {
            out.push_str(&format!("### Commit {}: `{}`\n\n", commit.index, commit.title));
            out.push_str(&format!("- **Type**: `{}`\n", commit.commit_type.as_str()));
            out.push_str(&format!("- **Scope**: `{}`\n", commit.scope));
            out.push_str(&format!("- **Files Modified** ({}):\n", commit.files.len()));
            for file in &commit.files {
                out.push_str(&format!("  * `{}`\n", file));
            }
            if !commit.body.is_empty() {
                out.push_str("- **Changes Summary**:\n");
                for line in &commit.body {
                    out.push_str(&format!("  {}\n", line));
                }
            }
            out.push_str("\n");
        }

        out
    }

    pub fn format_shell(plan: &CommitPlan, dry_run: bool) -> String {
        let mut out = String::new();
        out.push_str("#!/usr/bin/env bash\n");
        out.push_str("# Auto-generated by vibe-commit\n");
        out.push_str("set -euo pipefail\n\n");

        if dry_run {
            out.push_str("echo \"[DRY RUN] Simulating atomic conventional commit application...\"\n\n");
        }

        for commit in &plan.commits {
            out.push_str(&format!("# Commit {}: {}\n", commit.index, commit.title));
            if dry_run {
                out.push_str(&format!("echo \"[DRY-RUN] Would stage and commit: {}\"\n", commit.title));
                for f in &commit.files {
                    out.push_str(&format!("echo \"  -> staged {}\"\n", f));
                }
            } else {
                for f in &commit.files {
                    out.push_str(&format!("git add \"{}\"\n", f));
                }
                let body_escaped = commit.body.join("\n");
                if body_escaped.is_empty() {
                    out.push_str(&format!("git commit -m \"{}\"\n\n", commit.title));
                } else {
                    out.push_str(&format!(
                        "git commit -m \"{}\" -m \"{}\"\n\n",
                        commit.title, body_escaped
                    ));
                }
            }
        }

        if dry_run {
            out.push_str("echo \"[DRY RUN] Finished verification of all commits.\"\n");
        } else {
            out.push_str("echo \"Successfully created all atomic conventional commits!\"\n");
        }

        out
    }
}
